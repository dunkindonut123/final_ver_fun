export function generateWordSet(level: HSKLevel, count: number = 24): string[] {
  // Use 2-character compound words
  const wordPool = hsk2CharWords[level]
  const words: string[] = []
  
  // If not enough unique words, we'll need to allow some repetition
  if (wordPool.length < count) {
    // Fill with all unique words first, then repeat
    const allWords = [...wordPool]
    while (words.length < count) {
      const randomIndex = Math.floor(Math.random() * allWords.length)
      words.push(allWords[randomIndex])
    }
  } else {
    // Get unique words without duplicates
    const usedIndices = new Set<number>()
    while (words.length < count) {
      const randomIndex = Math.floor(Math.random() * wordPool.length)
      if (!usedIndices.has(randomIndex)) {
        usedIndices.add(randomIndex)
        words.push(wordPool[randomIndex])
      }
    }
  }
  return words
}
